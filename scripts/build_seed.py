def main():
    tax_path = os.path.join(ROOT, "data", "taxonomy.json")
    if os.path.isfile(tax_path):
        with open(tax_path, "r", encoding="utf-8") as fh:
            taxonomy = json.load(fh)
    else:
        with open(os.path.join(ROOT, "seed", "notebook.json"), encoding="utf-8") as fh:
            taxonomy = json.load(fh)["taxonomy"]

    notebook = {
        "house_name": "littlechef",
        "house_subtitle": "家庭菜谱",
        "taxonomy": taxonomy,
        "recipes": RECIPES,
        "pantry": PANTRY,
        "menus": [],
    }

    out = os.path.join(ROOT, "seed", "notebook.json")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(notebook, fh, ensure_ascii=False, indent=2)
        fh.write("\n")

    roles = {}
    for r in RECIPES:
        for role in r["course_role"]:
            roles[role] = roles.get(role, 0) + 1
    print("wrote %s" % out)
    print("recipes: %d   pantry: %d" % (len(RECIPES), len(PANTRY)))
    print("course roles:", roles)
    missing = [r["id"] for r in RECIPES if not r["image"]]
    print("no illustration yet:", missing)


if __name__ == "__main__":
    main()
